import { MCPServer } from 'mcp-use';
import { Client, StreamableHTTPClientTransport } from '@modelcontextprotocol/client';
import { z } from 'zod';
const server = new MCPServer({ name: 'probe', version: '0.0.1', host: '127.0.0.1', port: 0, basePath: '/mcp', legacy: 'stateless', logging: { enabled: false } } as never);
(server as any).__primeViews({ factory: { kind: 'inline', js: 'console.log("hi")', css: 'body{background:#000}' } });
server.tool({ name: 'show_factory', description: 'show it', inputSchema: z.object({ siteId: z.string() }), outputSchema: z.object({ siteId: z.string() }), view: { name: 'factory', description: 'Factory scan', csp: { resourceDomains: ['https://cdn.jsdelivr.net'], connectDomains: ['https://d28zzqy0iyovbz.cloudfront.net'] }, prefersBorder: false } } as never, async ({ siteId }: { siteId: string }) => ({ content: [{ type: 'text', text: 'x' }], structuredContent: { siteId } }) as never);
const listener = await server.listen(0, { host: '127.0.0.1' });
const c = new Client({ name: 'p', version: '1' }, { capabilities: {} });
await c.connect(new StreamableHTTPClientTransport(new URL(listener.url)));
const t = (await c.listTools()).tools[0]!;
console.log('tool meta', JSON.stringify(t._meta));
const rs = await c.listResources();
console.log('resources', JSON.stringify(rs.resources));
const uri = rs.resources[0]!.uri;
const r = await c.readResource({ uri });
console.log('read', JSON.stringify(r).slice(0, 2500));
const call = await c.callTool({ name: 'show_factory', arguments: { siteId: 'myer-plant' } });
console.log('call', JSON.stringify(call));
await c.close(); await server.close(); process.exit(0);
